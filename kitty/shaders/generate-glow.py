#!/usr/bin/env python3
"""Generate tux-glow.slang and tux-glow.pipeline from glow-colors.toml.

Usage: edit glow-colors.toml, then run:
    python3 generate-glow.py [--output-dir DIR]

Writes tux-glow.slang and tux-glow.pipeline next to this script (or into
--output-dir). Copy both to ~/.config/kitty/shaders/ and restart kitty.
"""

import argparse
import pathlib
import tomllib

HERE = pathlib.Path(__file__).resolve().parent


def srgb_to_linear(channel: float) -> float:
    if channel <= 0.04045:
        return channel / 12.92
    return ((channel + 0.055) / 1.055) ** 2.4


def hex_to_linear(hex_str: str) -> tuple[float, float, float]:
    h = hex_str.lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) / 255.0 for i in (0, 2, 4))
    return srgb_to_linear(r), srgb_to_linear(g), srgb_to_linear(b)


HEADER = """\
#language slang 2026
// Tux Ninja — neon text glow for Kitty.
// GENERATED by generate-glow.py from glow-colors.toml — do not edit by hand;
// edit glow-colors.toml and re-run the generator instead.
//
// Matches pixels against the theme's named palette colors (with antialiasing
// awareness: a pixel anywhere on the blend line between the background and a
// named color counts as that color) and applies a per-color glow with
// per-color strength and radius.

import kitty_custom_shader_types;
"""

SAMPLES = """
// Golden spiral sample pattern [x, y, weight] — weight is inverse of distance
static const float3 samples[24] = {
    float3(0.1693761725038636, 0.9855514761735895, 1.0),
    float3(-1.333070830962943, 0.4721463328627773, 0.7071067811865475),
    float3(-0.8464394909806497, -1.51113870578065, 0.5773502691896258),
    float3(1.554155680728463, -1.2588090085709776, 0.5),
    float3(1.681364377589461, 1.4741145918052656, 0.4472135954999579),
    float3(-1.2795157692199817, 2.088741103228784, 0.4082482904638631),
    float3(-2.4575847530631187, -0.9799373355024756, 0.3779644730092272),
    float3(0.5874641440208847, -2.7667464429345077, 0.35355339059327373),
    float3(2.997715703369726, 0.11704939884745152, 0.3333333333333333),
    float3(0.41360842451688395, 3.1351121305574803, 0.31622776601683794),
    float3(-3.167149933769243, 0.9844599011770256, 0.30151134457776363),
    float3(-1.5736713846521535, -3.0860263079123245, 0.2886751345948129),
    float3(2.888202648340422, -2.1583061557896213, 0.2773500981126146),
    float3(2.7150778983300325, 2.5745586041105715, 0.2672612419124244),
    float3(-2.1504069972377464, 3.2211410627650165, 0.2581988897471611),
    float3(-3.6548858794907493, -1.6253643308191343, 0.25),
    float3(1.0130775986052671, -3.9967078676335834, 0.24253562503633297),
    float3(4.229723673607257, 0.33081361055181563, 0.23570226039551587),
    float3(0.40107790291173834, 4.340407413572593, 0.22941573387056174),
    float3(-4.319124570236028, 1.1598115996934382, 0.22360679774997896),
    float3(-1.9209044802827355, -4.160543952132907, 0.2182178902359924),
    float3(3.8639122286635708, -2.6589814382925123, 0.21320071635561041),
    float3(3.3486228404946234, 3.4331800232609, 0.20851441405707477),
    float3(-2.8769733643574344, 3.9652268864187157, 0.20412414523193154)
};
"""

FOOTER = """
// --- Implementation ---

// distance² from a pixel to the blend segment between the background bg and
// a theme color c, plus the blend factor t. Antialiased glyph pixels are
// blends t*c + (1-t)*bg for some t in [0,1], so any pixel on that segment is
// "this color". t is 0 at the background itself and 1 at the pure color.
void
segment_match(float3 p, float3 bg, float3 c, out float dist2, out float t) {
    float3 cb = c - bg;
    t = clamp(dot(p - bg, cb) / max(dot(cb, cb), 1e-6f), 0.0f, 1.0f);
    float3 closest = bg + t * cb;
    float3 diff = p - closest;
    dist2 = dot(diff, diff);
}

public float4
fragment_main(float4 color, KittyTextures t, KittyCustomShaderData d) {
    float2 uv = t.pos;

    // One pixel in backbuffer UV space
    float2 base = (1.414f) / float2(d.viewport_size_pixels);
    float3 bg = d.background.rgb;

    float4 result = color;

    [ForceUnroll]
    for (int i = 0; i < 24; i++) {
        float3 s = samples[i];
        // single texture fetch per tap
        float2 off = s.xy * base;
        float dist2 = dot(off, off);
        float4 sc = t.backbuffer.Sample(uv + off);

        [ForceUnroll]
        for (int j = 0; j < NUM_GLOW_COLORS; j++) {
            float strength = glow_strengths[j];
            if (strength <= 0.0f) { continue; }
            float dd, blend_t;
            segment_match(sc.rgb, bg, glow_colors[j], dd, blend_t);
            // soft match weight: 1 at the color, ~0 beyond the tolerance.
            // scaled by blend_t so the pure background (t=0) never glows.
            float q = dd / TOLERANCE2;
            float match = blend_t / ((1.0f + q) * (1.0f + q));
            // per-color radius falloff
            float r = glow_radii[j];
            float w = 1.0f / (1.0f + 2.0f * dist2 / (r * r));
            result += float4(glow_colors[j], sc.a)
                * (strength * s.z * match * w);
        }

        // catch-all: pixels that match no palette color but are clearly
        // distinct from the background (dircolors, foreign hues) glow
        // faintly in their own color
        if (CATCHALL_STRENGTH > 0.0f) {
            float bg_dist = length(sc.rgb - bg) / (TOLERANCE * 4.0f);
            float fallback = clamp(bg_dist - 1.0f, 0.0f, 1.0f);
            float cw = 1.0f / (1.0f + 2.0f * dist2 / (CATCHALL_RADIUS * CATCHALL_RADIUS));
            result += sc * (CATCHALL_STRENGTH * s.z * fallback * cw);
        }
    }

    return result;
}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=HERE / "glow-colors.toml")
    ap.add_argument("--output-dir", type=pathlib.Path, default=HERE)
    args = ap.parse_args()

    with open(args.config, "rb") as f:
        cfg = tomllib.load(f)

    tolerance = float(cfg.get("settings", {}).get("tolerance", 0.10))
    colors = cfg.get("colors", {})
    if not colors:
        raise SystemExit("no [colors.*] entries found in glow-colors.toml")

    names = list(colors)
    linear = {n: hex_to_linear(c["hex"]) for n, c in colors.items()}

    parts = [HEADER]
    parts.append(f"static const int NUM_GLOW_COLORS = {len(names)};\n")
    parts.append(f"static const float TOLERANCE = {tolerance:.4f}f;")
    parts.append("static const float TOLERANCE2 = TOLERANCE * TOLERANCE;")
    catchall_strength = float(cfg.get("settings", {}).get("catchall_strength", 0.0))
    catchall_radius = float(cfg.get("settings", {}).get("catchall_radius", 1.0))
    parts.append(f"static const float CATCHALL_STRENGTH = {catchall_strength:.4f}f;")
    parts.append(f"static const float CATCHALL_RADIUS = {catchall_radius:.4f}f;")

    parts.append("// palette colors, linear RGB — hex values from glow-colors.toml")
    parts.append("static const float3 glow_colors[NUM_GLOW_COLORS] = {")
    for n in names:
        r, g, b = linear[n]
        parts.append(f"    float3({r:.4f}f, {g:.4f}f, {b:.4f}f), // {n}")
    parts.append("};\n")

    # strengths/radii are static consts so they stay tunable via pipeline vars
    parts.append("// per-color glow strength (0 = off) — override via pipeline vars")
    parts.append("static const float glow_strengths[NUM_GLOW_COLORS] = {")
    for n in names:
        parts.append(f"    STRENGTH_{n.upper()},")
    parts.append("};\n")
    parts.append("// per-color glow radius (bloom steps) — override via pipeline vars")
    parts.append("static const float glow_radii[NUM_GLOW_COLORS] = {")
    for n in names:
        parts.append(f"    RADIUS_{n.upper()},")
    parts.append("};")

    for n in names:
        parts.append(f"static const float STRENGTH_{n.upper()} = {float(colors[n]['strength']):.4f}f;")
        parts.append(f"static const float RADIUS_{n.upper()} = {float(colors[n]['radius']):.4f}f;")

    parts.append(SAMPLES)
    parts.append(FOOTER)
    (args.output_dir / "tux-glow.slang").write_text("\n".join(parts))

    pipe = ["# Tux Ninja — neon text glow pipeline. GENERATED from glow-colors.toml.",
            "# Strengths and radii can be tuned here without regenerating the shader.", ""]
    pipe.append("startgroup")
    pipe.append("    # static effect: redraws only when content changes, no idle cost")
    pipe.append("    animation_step 0")
    pipe.append(f"    var float CATCHALL_STRENGTH = {catchall_strength:.4f}")
    pipe.append(f"    var float CATCHALL_RADIUS = {catchall_radius:.4f}")
    for n in names:
        pipe.append(f"    var float STRENGTH_{n.upper()} = {float(colors[n]['strength']):.4f}")
        pipe.append(f"    var float RADIUS_{n.upper()} = {float(colors[n]['radius']):.4f}")
    pipe.append("    shaders tux-glow")
    pipe.append("endgroup")
    (args.output_dir / "tux-glow.pipeline").write_text("\n".join(pipe) + "\n")

    print(f"wrote {args.output_dir}/tux-glow.slang and tux-glow.pipeline")
    for n in names:
        on = "on " if float(colors[n]["strength"]) > 0 else "off"
        print(f"  {on}  {n:<18} {colors[n]['hex']}  strength={colors[n]['strength']} radius={colors[n]['radius']}")


if __name__ == "__main__":
    main()
