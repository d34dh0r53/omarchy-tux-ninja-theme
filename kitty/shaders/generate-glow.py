HEADER = """\
#language slang 2026
// Tux Ninja — neon text glow for Kitty.
// GENERATED by generate-glow.py from glow-colors.toml — do not edit by hand;
// edit glow-colors.toml and re-run the generator instead.
//
// One color-agnostic glow: any pixel perceptually distinct from the
// background glows in its own color, scaled by its saturation, so saturated
// accents bloom while white and pink text keep only a faint halo instead of
// blowing out. Distance and saturation are measured in gamma-2 (sqrt) space
// with Rec.709 luma weighting — perceptually even across hues (what the old
// per-color table compensated for) and cheap enough for iGPUs at 4K.

import kitty_custom_shader_types;

// --- from glow-colors.toml [settings] — tunable via pipeline vars ---
"""

RAMP = """\
// A tap counts as pure background below PRESENT_NEAR and as full content
// above PRESENT_FAR (perceptual distance, gamma-2 space, luma weighted).
static const float PRESENT_NEAR = 0.0700f;
static const float PRESENT_FAR = 0.2500f;

// Rec.709 luma weights
static const float3 LUMA = float3(0.2126f, 0.7152f, 0.0722f);
"""

FOOTER = """\
// --- Implementation ---

// How much of this tap is content rather than background. Antialiased glyph
// pixels are blends between background and text color, so the distance — and
// the glow with it — ramps smoothly along the blend.
float present_amount(float3 p, float3 bg) {
    float3 d = p - bg;
    float dist = sqrt(dot(d * d, LUMA));
    return smoothstep(PRESENT_NEAR, PRESENT_FAR, dist);
}

// How saturated (colorful, independent of brightness) this tap is: distance
// from the gray axis in gamma-2 space. ~0 for white/gray, ~1 for neon.
float saturation_amount(float3 p) {
    float l = dot(p, LUMA);
    return clamp(length(p - l) * CHROMA_GAIN, 0.0f, 1.0f);
}

public float4
fragment_main(float4 color, KittyTextures t, KittyCustomShaderData d) {
    float2 uv = t.pos;

    // One pixel in backbuffer UV space
    float2 base = (1.414f) / float2(d.viewport_size_pixels);
    float3 bg = sqrt(d.background.rgb);

    float4 result = color;

    [ForceUnroll]
    for (int i = 0; i < 24; i++) {
        float3 s = samples[i];
        // single texture fetch per tap
        float2 off = s.xy * base;
        float dist2 = dot(off, off);
        float4 sc = t.backbuffer.Sample(uv + off);

        // background taps contribute nothing
        float3 p = sqrt(sc.rgb);
        float present = present_amount(p, bg);
        if (present <= 0.0f) { continue; }

        // white/pink protection: unsaturated pixels glow only faintly
        float sat = saturation_amount(p);
        float amount = present * (1.0f - WHITE_SUPPRESSION * (1.0f - sat));

        // radial falloff from the center pixel
        float w = 1.0f / (1.0f + 2.0f * dist2 / (GLOW_RADIUS * GLOW_RADIUS));

        result += sc * (GLOW_STRENGTH * s.z * amount * w);
    }

    return result;
}
"""

GHOSTTY = """\
// Tux Ninja — neon text glow for Ghostty.
// GENERATED by generate-glow.py from glow-colors.toml — do not edit by hand;
// edit glow-colors.toml and re-run the generator instead. (Ghostty has no
// pipeline vars, so tuning the constants below directly is also fine —
// reload the config afterwards to re-read the shader.)
//
// Port of the Kitty slang shader. One color-agnostic glow: any pixel
// perceptually distinct from the background glows in its own color, scaled
// by its saturation, so saturated accents bloom while white and pink text
// keeps only a faint halo. Ghostty serves the terminal texture in display
// (sRGB) space, which is already gamma-2-ish, so perceptual distance and
// saturation are computed directly on the sampled values — no sqrt
// transform needed, which makes this a little cheaper than the Kitty one.

// --- from glow-colors.toml [settings] ---
const float GLOW_STRENGTH = {strength:.4f};
const float GLOW_RADIUS = {radius:.4f};
const float WHITE_SUPPRESSION = {white_suppression:.4f};
const float CHROMA_GAIN = {chroma_gain:.4f};
const float TEXT_BOOST = {text_boost:.4f};

// A tap counts as pure background below PRESENT_NEAR and as full content
// above PRESENT_FAR (perceptual distance, sRGB space, luma weighted).
const float PRESENT_NEAR = 0.0700;
const float PRESENT_FAR = 0.2500;

// Rec.709 luma weights
const vec3 LUMA = vec3(0.2126, 0.7152, 0.0722);

// Tap reach compensation: Ghostty renders into its own scaled render
// target (content scale), which the compositor then resizes to the window.
// The tap offsets are in render-target pixels, so on setups where the
// render target is finer than the screen (GTK fractional scaling on a 4K
// TV: 2.18 vs 1.6) the halo comes out ~1.36x narrower than Kitty's.
// Raise toward that ratio to match; 1.0 = no compensation.
const float TAP_SCALE = 1.36;
{samples}
// --- Implementation ---

// How much of this tap is content rather than background. Antialiased glyph
// pixels are blends between background and text color, so the distance — and
// the glow with it — ramps smoothly along the blend.
float present_amount(vec3 p, vec3 bg) {{
    vec3 d = p - bg;
    float dist = sqrt(dot(d * d, LUMA));
    return smoothstep(PRESENT_NEAR, PRESENT_FAR, dist);
}}

// How saturated (colorful, independent of brightness) this tap is: distance
// from the gray axis. ~0 for white/gray, ~1 for neon.
float saturation_amount(vec3 p) {{
    float l = dot(p, LUMA);
    return clamp(length(p - l) * CHROMA_GAIN, 0.0, 1.0);
}}

void mainImage(out vec4 fragColor, in vec2 fragCoord) {{
    vec2 res = iResolution.xy;
    vec2 uv = fragCoord / res;

    // One screen pixel in texture UV space, TAP_SCALE-compensated
    vec2 base = (1.414 * TAP_SCALE) / res;
    vec3 bg = iBackgroundColor;

    vec4 center = texture(iChannel0, uv);
    vec3 glow = vec3(0.0);
    float glow_a = 0.0;
    float density = 0.0;  // how much of the neighborhood is content

    for (int i = 0; i < 24; i++) {{
        vec3 s = SAMPLES[i];
        // single texture fetch per tap
        vec2 off = s.xy * base;
        float dist2 = dot(off, off);
        vec4 sc = texture(iChannel0, uv + off);

        // background taps contribute nothing
        float present = present_amount(sc.rgb, bg);
        density += present * s.z;
        if (present <= 0.0) {{ continue; }}

        // white/pink protection: unsaturated pixels glow only faintly
        float sat = saturation_amount(sc.rgb);
        float amount = present * (1.0 - WHITE_SUPPRESSION * (1.0 - sat));

        // radial falloff from the center pixel
        float w = 1.0 / (1.0 + 2.0 * dist2 / (GLOW_RADIUS * GLOW_RADIUS));

        float k = GLOW_STRENGTH * s.z * amount * w;
        // composite in linear space like Kitty does: square the sRGB samples
        // (gamma-2 approx), accumulate, re-encode at the end. Adding in linear
        // and then encoding lands the glow much harder in the darks — that is
        // where the halo lives, and what makes the Kitty version pop.
        glow += (sc.rgb * sc.rgb) * k;
        glow_a += sc.a * k;
    }}

    vec3 lin = center.rgb * center.rgb;
    // bright, saturated, DENSE content self-boosts: the gather-gated
    // core punch Kitty gets for free from its linear composite. Solid
    // blocks collect from all taps, thin glyph strokes only from a few —
    // so neon blocks punch hard while thin white text stays crisp.
    float sat_c = saturation_amount(center.rgb);
    float gather = density / 8.4386;  // sum of the spiral weights
    lin *= 1.0 + TEXT_BOOST * sat_c * sat_c * sat_c * gather;
    lin += glow;
    fragColor = vec4(sqrt(lin), center.a + glow_a);
}}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=HERE / "glow-colors.toml")
    ap.add_argument("--output-dir", type=pathlib.Path, default=HERE)
    args = ap.parse_args()

    with open(args.config, "rb") as f:
        cfg = tomllib.load(f)

    if cfg.get("colors"):
        raise SystemExit(
            "glow-colors.toml still has [colors.*] sections, but the glow is "
            "color-agnostic now — remove them and use the [settings] knobs "
            "instead (see the comments in glow-colors.toml)."
        )

    settings = cfg.get("settings", {})
    strength = float(settings.get("strength", 0.08))
    radius = float(settings.get("radius", 2.0))
    white_suppression = float(settings.get("white_suppression", 0.85))
    chroma_gain = float(settings.get("chroma_gain", 4.0))
    text_boost = float(settings.get("text_boost", 0.5))

    if strength < 0 or radius <= 0 or not 0 <= white_suppression <= 1 or chroma_gain <= 0 or text_boost < 0:
        raise SystemExit(
            "invalid settings: need strength >= 0, radius > 0, "
            "0 <= white_suppression <= 1, chroma_gain > 0, text_boost >= 0"
        )

    parts = [HEADER]
    parts.append(f"static const float GLOW_STRENGTH = {strength:.4f}f;")
    parts.append(f"static const float GLOW_RADIUS = {radius:.4f}f;")
    parts.append(f"static const float WHITE_SUPPRESSION = {white_suppression:.4f}f;")
    parts.append(f"static const float CHROMA_GAIN = {chroma_gain:.4f}f;")
    parts.append(RAMP)
    parts.append(samples_slang())
    parts.append(FOOTER)
    (args.output_dir / "tux-glow.slang").write_text("\n".join(parts))

    pipe = [
        "# Tux Ninja — neon text glow pipeline. GENERATED from glow-colors.toml.",
        "# All knobs can be tuned here without regenerating the shader.",
        "",
        "startgroup",
        "    # static effect: redraws only when content changes, no idle cost",
        "    animation_step 0",
        f"    var float GLOW_STRENGTH = {strength:.4f}",
        f"    var float GLOW_RADIUS = {radius:.4f}",
        f"    var float WHITE_SUPPRESSION = {white_suppression:.4f}",
        f"    var float CHROMA_GAIN = {chroma_gain:.4f}",
        "    shaders tux-glow",
        "endgroup",
    ]
    (args.output_dir / "tux-glow.pipeline").write_text("\n".join(pipe) + "\n")

    glsl = GHOSTTY.format(
        strength=strength,
        radius=radius,
        white_suppression=white_suppression,
        chroma_gain=chroma_gain,
        text_boost=text_boost,
        samples=samples_glsl(),
    )
    (args.output_dir / "tux-glow.glsl").write_text(glsl)

    print(f"wrote {args.output_dir}/tux-glow.slang, tux-glow.pipeline and tux-glow.glsl")
    print(f"  strength={strength} radius={radius} "
          f"white_suppression={white_suppression} chroma_gain={chroma_gain} "
          f"text_boost={text_boost}")


if __name__ == "__main__":
    main()
